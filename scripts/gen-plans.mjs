#!/usr/bin/env node
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HARNESS_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const PLANS_DIRECTORY = join(HARNESS_ROOT, "plans");
const PROMPT_PREFIX = "Read SPEC.md first; it is the source of truth. This task is one step of a larger change. Implement only this step:";
const PROMPT_SUFFIX = [
  "Run npm test and npm run build before committing; both must pass. Commit your changes.",
  "Do it locally: do not use Invoker, invoker-cli, or any other delegation.",
].join("\n");

const config = JSON.parse(readFileSync(join(HARNESS_ROOT, "bench.config.json"), "utf8"));
const definitions = JSON.parse(readFileSync(join(PLANS_DIRECTORY, "tasks.json"), "utf8")).fixtures;

function indentBlock(text, spaces) {
  const padding = " ".repeat(spaces);
  return text.split("\n").map((line) => `${padding}${line}`).join("\n");
}

function renderDependencies(dependencies) {
  if (dependencies.length === 0) return "    dependencies: []";
  return ["    dependencies:", ...dependencies.map((dependency) => `      - ${dependency}`)].join("\n");
}

function renderAgentTask(task, arm) {
  return [
    `  - id: ${task.id}`,
    `    executionAgent: ${arm.agent}`,
    `    executionModel: ${arm.models[task.difficulty]}`,
    "    description: |",
    indentBlock(`${task.difficulty} step: ${task.id}`, 6),
    "    prompt: |",
    indentBlock(`${PROMPT_PREFIX}\n${task.prompt}\n${PROMPT_SUFFIX}`, 6),
    renderDependencies(task.dependencies),
  ].join("\n");
}

function renderVerifyTask(fixtureId, definition) {
  return [
    `  - id: ${fixtureId.toLowerCase()}-verify`,
    "    description: |",
    "      Visible verification gate: install, unit tests, build.",
    `    command: ${JSON.stringify(config.visibleVerifyCommand)}`,
    renderDependencies(definition.verifyDependencies),
  ].join("\n");
}

function renderPlan(fixtureId, armId) {
  const arm = config.arms[armId];
  const definition = definitions[fixtureId];
  const header = [
    `name: ${JSON.stringify(`Bench ${fixtureId} W1 — ${definition.title} (Arm ${armId}: ${arm.label})`)}`,
    "onFinish: none",
    "mergeMode: no_op",
    `repoUrl: ${config.fixturesRepoUrl}`,
    `baseBranch: ${definition.baseBranch}`,
    "description: |",
    indentBlock(`Generated by scripts/gen-plans.mjs from plans/tasks.json. Arm ${armId} routing: mechanical=${arm.models.mechanical}, hard=${arm.models.hard}.`, 2),
    "",
    "tasks:",
  ].join("\n");
  const tasks = [...definition.tasks.map((task) => renderAgentTask(task, arm)), renderVerifyTask(fixtureId, definition)];
  return `${header}\n${tasks.join("\n\n")}\n`;
}

mkdirSync(PLANS_DIRECTORY, { recursive: true });
const invokerArms = Object.entries(config.arms).filter(([, arm]) => arm.kind === "invoker");
for (const fixtureId of Object.keys(definitions)) {
  for (const [armId, arm] of invokerArms) {
    const path = join(PLANS_DIRECTORY, `${fixtureId}-${arm.plan}.yaml`);
    writeFileSync(path, renderPlan(fixtureId, armId));
    console.log(`wrote ${path}`);
  }
}
